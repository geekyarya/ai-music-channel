"""Daily pipeline: idea → lyrics → song → music video → thumbnail → YouTube."""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import video  # noqa: E402
import youtube  # noqa: E402
from music import make_song  # noqa: E402
from songwriter import lyrics_text, write_song  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HISTORY = os.path.join(ROOT, "data", "history.json")


def load_history() -> list[dict]:
    try:
        with open(HISTORY) as fh:
            return json.load(fh)
    except FileNotFoundError:
        return []


def build_description(spec: dict, cfg: dict, engine: str) -> str:
    ch, disclose = cfg["channel"], cfg["channel"].get("disclose_ai", False)
    lines = [spec["description"], ""]
    if cfg["youtube"].get("engagement_line"):
        lines += [cfg["youtube"]["engagement_line"], ""]
    lines += [
        f"🎧 {spec['title']} — {ch['artist']}",
        f"Genre: {spec['genre']}  |  Language: {spec['language_name']}  |  Mood: {spec['mood']}  |  {spec['bpm']} BPM",
        "",
        "📝 LYRICS",
        lyrics_text(spec).replace("[", "(").replace("]", ")"),
        "",
    ]
    if disclose:
        lines += [
            "🤖 HOW THIS WAS MADE",
            f"Everything on {ch['name']} is generated by AI, automatically, every day.",
            "Lyrics & concept: large language model",
            f"Music & vocals: {engine}",
            "Visuals: procedural audio-reactive animation",
            "",
        ]
    tags = spec["hashtags"] + (["#aimusic", "#aisong"] if disclose else ["#newmusic"]) \
        + (["#hindisong"] if spec["language"] != "en" else [])
    lines.append(" ".join(dict.fromkeys(tags)))
    return "\n".join(lines)


def normalize_old_spec(spec: dict, cfg: dict) -> dict:
    """Fill fields that songs made by older versions of the pipeline may lack, and apply today's AI-wording rules."""
    from songwriter import _scrub
    spec.setdefault("language", "en")
    spec.setdefault("language_name", {"hi": "Hindi", "hinglish": "Hinglish"}.get(spec["language"], "English"))
    spec.setdefault("song_type", "rap" if any(k in spec.get("genre", "") for k in ("rap", "trap", "drill", "hip"))
                    else "sung")
    spec.setdefault("hashtags", [])
    spec.setdefault("description", "")
    spec.setdefault("mood", "")
    return _scrub(spec, cfg)


def build_metadata(spec: dict, cfg: dict, engine: str) -> tuple[str, str, list[str]]:
    """YouTube title, description and tags for a song."""
    disclose = cfg["channel"].get("disclose_ai", False)
    label = {"hi": "Hindi", "hinglish": "Hindi"}.get(spec["language"], "")
    kind = " ".join(x for x in (spec["genre"].title(), label, "AI Song" if disclose else "Song") if x)
    title = f"{spec['title']} | {cfg['channel']['artist']} ({kind})"
    desc = build_description(spec, cfg, engine)
    tags = cfg["youtube"]["default_tags"] + (cfg["youtube"].get("ai_tags", []) if disclose else []) \
        + [spec["genre"], f"{spec['genre']} song", spec["title"]] + [t.lstrip("#") for t in spec["hashtags"]]
    if spec["language"] != "en":
        tags += ["hindi song", "new hindi song", "hindi rap" if spec["song_type"] == "rap" else "hindi gaana"]
        if disclose:
            tags.append("hindi ai song")
    return title, desc, tags


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--genre", help="force a genre for this run")
    ap.add_argument("--language", help="force a language: en | hi | hinglish")
    ap.add_argument("--type", choices=["rap", "sung"], help="force rap or a sung song")
    ap.add_argument("--backend", choices=["ace_step", "local"], help="force a music backend")
    ap.add_argument("--offline", action="store_true", help="skip the LLM (built-in test lyrics)")
    ap.add_argument("--no-upload", action="store_true")
    ap.add_argument("--seconds", type=float, help="truncate video length (for quick tests)")
    args = ap.parse_args()

    with open(os.path.join(ROOT, "config.yaml")) as fh:
        cfg = yaml.safe_load(fh)
    history = load_history()

    print("✍️  writing song…")
    spec = write_song(cfg, history, args.genre, offline=args.offline, language=args.language,
                      song_type=args.type)
    print(f"   “{spec['title']}” — {spec['language_name']} {spec['song_type']} / {spec['genre']} / "
          f"{spec['mood']} / {spec['bpm']} BPM / {spec['visual_style']}")

    slug = re.sub(r"[^a-z0-9]+", "-", spec["title"].lower()).strip("-")[:40]
    out = os.path.join(ROOT, "out", f"{dt.date.today():%Y-%m-%d}-{slug}")
    os.makedirs(out, exist_ok=True)

    song = make_song(spec, cfg, out, only=args.backend)
    print(f"   engine: {song['engine']}")
    audio = song["audio"]
    if args.seconds:
        import subprocess
        cut = os.path.join(out, "song_cut.wav")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", audio, "-t", str(args.seconds), cut], check=True)
        audio = cut

    mp4 = video.render(spec, cfg, audio, song["timings"], os.path.join(out, "video.mp4"))
    thumb = video.thumbnail(spec, cfg, audio, os.path.join(out, "thumbnail.jpg"))

    title, desc, tags = build_metadata(spec, cfg, song["engine"])
    with open(os.path.join(out, "spec.json"), "w") as fh:
        json.dump({**spec, "engine": song["engine"], "timings": song["timings"], "yt_title": title,
                   "yt_description": desc}, fh, indent=2)

    # Vertical reel (Instagram Reels + YouTube Shorts) from the best ~45 s of the song.
    reel_path = None
    if cfg.get("reels", {}).get("enabled", True):
        import reel
        reel_path = reel.make_reel(spec, cfg, audio, song["timings"], out)

    # Each upload is independent: one failing must not stop the others. Failures fail the run at the end.
    errors, video_id, short_id, ig_link = [], None, None, None
    yt_lang = "hi" if spec["language"] != "en" else "en"
    if args.no_upload:
        print("⏭  uploads skipped (--no-upload)")
    else:
        if not youtube.have_credentials():
            print("⚠️  YT_CLIENT_ID / YT_CLIENT_SECRET / YT_REFRESH_TOKEN not set — skipping YouTube")
        else:
            try:
                print("📤 uploading to YouTube…")
                video_id = youtube.upload(mp4, thumb, title, desc, tags, cfg, language=yt_lang)
            except Exception as e:  # noqa: BLE001
                errors.append(f"YouTube video: {e}")
            if reel_path and cfg["reels"].get("youtube_shorts", True):
                try:
                    print("📤 uploading YouTube Short…")
                    short_desc = "\n".join(filter(None, [spec["description"], cfg["youtube"].get("engagement_line"),
                                 f"Full song on the channel 🎧", " ".join(spec["hashtags"][:5] + ["#shorts"])]))
                    short_id = youtube.upload(reel_path, None, f"{spec['title']} 🎧 #shorts"[:100], short_desc,
                                              tags + ["shorts"], cfg, language=yt_lang)
                except Exception as e:  # noqa: BLE001
                    errors.append(f"YouTube Short: {e}")
        import instagram
        if reel_path and cfg.get("instagram", {}).get("enabled", True):
            if not instagram.have_credentials():
                print("⚠️  no Instagram token secret set — skipping Instagram")
            else:
                try:
                    print("📤 posting Instagram reel…")
                    ig_link = instagram.post_reel(reel_path, instagram.build_caption(spec, cfg), cfg)
                except Exception as e:  # noqa: BLE001
                    errors.append(f"Instagram: {e}")
        import facebook
        if reel_path and cfg.get("facebook", {}).get("enabled", True) and facebook.have_credentials():
            try:
                print("📤 posting Facebook Page reel…")
                facebook.post_reel(reel_path, instagram.build_caption(spec, cfg), cfg)
            except Exception as e:  # noqa: BLE001
                errors.append(f"Facebook: {e}")

    history.append({"date": dt.date.today().isoformat(), "title": spec["title"], "genre": spec["genre"],
                    "language": spec["language"], "type": spec["song_type"],
                    "theme": spec["theme"], "engine": song["engine"], "video_id": video_id,
                    "short_id": short_id, "instagram": ig_link})
    os.makedirs(os.path.dirname(HISTORY), exist_ok=True)
    with open(HISTORY, "w") as fh:
        json.dump(history, fh, indent=2)
    for e in errors:
        print(f"::error::{e}")
    print(f"🎉 done → {out}")
    if errors:
        sys.exit(1)


if __name__ == "__main__":
    main()
