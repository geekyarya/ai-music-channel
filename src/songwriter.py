NO_AI_RULE = ("Do NOT mention AI, artificial intelligence, algorithms, or how the song was made anywhere in "
              "the title, description or hashtags. Present it simply as a new song release.")

_AI_RE = re.compile(r"\b(A\.?I\.?|artificial[ -]intelligence|AI[- ]generated|generated by|algorithm\w*|"
                    r"machine[- ]made|neural|synthetic)\b", re.I)


def scrub_ai(text: str) -> str:
    """Drop whole sentences that mention AI / how the song was made."""
    parts = re.split(r"(?<=[.!?…])\s+", text or "")
    return " ".join(p for p in parts if not _AI_RE.search(p)).strip()


def _is_ai_tag(tag: str) -> bool:
    t = tag.lower().lstrip("#")
    return bool(re.fullmatch(r"ai(music|song|songs|generated|art|rap|cover|singer|artist|vocals)?", t)
                or "artificial" in t or "generated" in t)

